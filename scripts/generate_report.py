#!/usr/bin/env python3
"""Assembles reports/evaluation_report.md purely from the JSON files other scripts
already wrote to reports/metrics/. Never invents a number: any section whose JSON file
is missing is rendered as "not yet run" rather than skipped silently or guessed.

Usage:
    python scripts/generate_report.py
"""

import json
from pathlib import Path

METRICS_DIR = Path("reports/metrics")
OUT_PATH = Path("reports/evaluation_report.md")


def load(name: str) -> dict | None:
    path = METRICS_DIR / name
    return json.loads(path.read_text()) if path.exists() else None


def fmt(value, digits: int = 4) -> str:
    return f"{value:.{digits}f}" if isinstance(value, (int, float)) else "N/A"


def main() -> None:
    anomaly = load("anomaly_detection.json")
    classification = load("supervised_classification.json")
    calibration = load("calibration.json")
    active_learning = load("active_learning.json")

    lines = ["# Evaluation Report", "", "All numbers below are read directly from `reports/metrics/*.json`,", "generated by the scripts named in each section. None are hand-entered.", ""]

    lines += ["## Anomaly Detection (MVTec AD metal_nut, official protocol)", ""]
    if anomaly:
        c, p = anomaly["classical_baseline"], anomaly["patchcore_lite"]
        lines += [
            f"- Test set: n={anomaly['n_test']} ({anomaly['n_train_normal']} normal images used for training).",
            "",
            "| Model | Image AUROC | Image AUPRC | Pixel AUROC |",
            "|---|---:|---:|---:|",
            f"| Classical baseline | {fmt(c['image_auroc'])} | {fmt(c['image_auprc'])} | N/A |",
            f"| PatchCore-lite | {fmt(p['image_auroc'])} | {fmt(p['image_auprc'])} | {fmt(p.get('pixel_auroc'))} |",
            "",
            f"Image AUROC 95% CI (bootstrap): classical [{fmt(c['image_auroc_ci95'][0])}, {fmt(c['image_auroc_ci95'][1])}], "
            f"PatchCore-lite [{fmt(p['image_auroc_ci95'][0])}, {fmt(p['image_auroc_ci95'][1])}].",
        ]
    else:
        lines.append("_Not yet run. Run `python scripts/train_anomaly.py`._")
    lines.append("")

    lines += ["## Supervised Classification (labeled pool, held-out test)", ""]
    if classification:
        t = classification["test_metrics"]
        lines += [
            f"- Held-out test: n={classification['n_held_out_test']}, accuracy={fmt(t['accuracy'])}, macro-F1={fmt(t['macro_f1'])}.",
            "",
            "| Class | Precision | Recall | F1 | Support |",
            "|---|---:|---:|---:|---:|",
        ]
        for name, m in t["per_class"].items():
            lines.append(f"| {name} | {fmt(m['precision'])} | {fmt(m['recall'])} | {fmt(m['f1'])} | {m['support']} |")
    else:
        lines.append("_Not yet run. Run `python scripts/train.py`._")
    lines.append("")

    lines += ["## Calibration", ""]
    if calibration:
        lines += [
            f"- Raw ECE: {fmt(calibration['raw_ece'])}; temperature-scaled ECE (T={fmt(calibration['temperature'], 3)}): {fmt(calibration['calibrated_ece'])}.",
            f"- Selected human-review confidence threshold: {calibration['selected_review_threshold']} ({calibration['selection_rule']}).",
        ]
        if calibration["calibrated_ece"] > calibration["raw_ece"]:
            lines.append(
                "- **Note:** temperature scaling made calibration worse here, likely because it was "
                f"fit on only {calibration['n_val']} validation examples — too few for a stable estimate. "
                "See README limitations."
            )
    else:
        lines.append("_Not yet run. Run `python scripts/evaluate.py`._")
    lines.append("")

    lines += ["## Active Learning", ""]
    if active_learning:
        lines.append(
            f"- Pool: {active_learning['n_pool']} images, held-out test: {active_learning['n_held_out_test']}, "
            f"{active_learning['config']['n_repeats']} seeds per strategy."
        )
        lines += ["", "| Strategy | Final macro-F1 (mean ± std) |", "|---|---:|"]
        for strategy, runs in active_learning["results"].items():
            finals = [r["macro_f1"][-1] for r in runs]
            mean = sum(finals) / len(finals)
            std = (sum((x - mean) ** 2 for x in finals) / len(finals)) ** 0.5
            lines.append(f"| {strategy} | {fmt(mean)} ± {fmt(std)} |")
        lines.append("")
        lines.append(
            "See `reports/figures/active_learning_curves.png` for the full budget-vs-performance curves. "
            "Confidence bands overlap for most of the budget range, so this experiment does not "
            "demonstrate a statistically clear labeling-efficiency advantage for any strategy over random."
        )
    else:
        lines.append("_Not yet run. Run `python scripts/run_active_learning.py`._")
    lines.append("")

    OUT_PATH.write_text("\n".join(lines))
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
